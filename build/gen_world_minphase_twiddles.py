"""Generate the fixed 1024-point HLS FFT rotation ROM as float32 constants."""
import math
from pathlib import Path
import struct

def f32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0]

lines = ['// Generated by build/gen_world_minphase_twiddles.py; IEEE float32 constants.',
         '#ifndef WORLD_MINPHASE_TWIDDLES_H', '#define WORLD_MINPHASE_TWIDDLES_H']
for name, function in [('world_twiddle_re', math.cos), ('world_twiddle_im', math.sin)]:
    lines.append('static const float '+name+'[512] = {')
    for first in range(0, 512, 4):
        lines.append('  '+','.join(format(f32(function(-2*math.pi*k/1024)), '.9e')+'f'
                                   for k in range(first, first+4))+',')
    lines.append('};')
lines += ['#endif', '']
(Path(__file__).resolve().parents[1]/'src/hls/world_minphase_twiddles.h').write_text(
    '\n'.join(lines), encoding='utf-8')
