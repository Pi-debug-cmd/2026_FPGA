"""Generate software mirror of the checked-in RTL lookup tables."""
import argparse
from pathlib import Path
from gen_world_exp_vectors import EXP_LUT, COS_LUT, SIN_LUT
p=argparse.ArgumentParser()
p.add_argument('--out',type=Path,required=True)
args=p.parse_args()
args.out.write_text('// Generated by build/gen_world_exp_tables.py\n'+''.join(
    'static const int %s[%d] = {%s};\n'%(name,len(values),','.join(str(int(x)) for x in values))
    for name,values in [('exp_table',EXP_LUT),('cos_table',COS_LUT),('sin_table',SIN_LUT)]),encoding='ascii')
