#!/usr/bin/env python3
"""csv_to_md.py - render a long-format metrics CSV as markdown, one table per section.

    python3 csv_to_md.py ../metrics.csv ../summary.md
    python3 csv_to_md.py ../resource_timing.csv ../resource_timing.md

Reads the columns produced by collect_metrics.py and by hand-written metrics.csv
(section, metric, value, unit, source[, note, ...]). Unknown extra columns are
ignored, so both files can be rendered by the same tool.
"""
from __future__ import annotations

import csv
import sys
from collections import OrderedDict
from pathlib import Path

KEEP = ["config", "metric", "value", "unit", "runs", "sample_duration_s", "status", "source"]


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 2
    src, dst = Path(argv[1]), Path(argv[2])
    rows = list(csv.DictReader(src.open(encoding="utf-8")))
    if not rows:
        print("empty csv")
        return 1
    cols = [c for c in KEEP if c in rows[0]]
    groups: "OrderedDict[str, list]" = OrderedDict()
    for r in rows:
        groups.setdefault(r.get("section", "?"), []).append(r)

    out = ["# %s" % src.stem.replace("_", " "), ""]
    out.append("Generated by `metrics/scripts/csv_to_md.py` from `%s` (%d rows)." % (src.name, len(rows)))
    for sec, rs in groups.items():
        out += ["", "## %s" % sec, ""]
        out.append("| " + " | ".join(cols) + " |")
        out.append("|" + "|".join(["---"] * len(cols)) + "|")
        for r in rs:
            out.append("| " + " | ".join(str(r.get(c, "")).replace("|", "/") for c in cols) + " |")
    dst.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote %s (%d sections, %d rows)" % (dst, len(groups), len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
